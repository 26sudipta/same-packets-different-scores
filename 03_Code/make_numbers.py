# formatting

def n(x):
    return f"{int(round(float(x))):,}".replace(",", "{,}")


def f2(x):
    return f"{x:.2f}"


def f3(x):
    return f"{x:.3f}"


def sgn(s):
    """A minus sign in maths mode, so that negative numbers print with a real minus. A value
    that rounds to zero prints without a sign (no "-0.000")."""
    if s.startswith("-") and float(s) == 0:
        return s[1:]
    return f"${s}$" if s.startswith("-") else s


def s3(x):
    return sgn(f3(x))


def pct(x, d=0):
    return f"{100 * x:.{d}f}"


def rng(lo, hi):
    return lo if lo == hi else f"{lo} to {hi}"


def write(name, body, src):
    TAB.mkdir(parents=True, exist_ok=True)
    p = TAB / name
    p.write_text(HEADER.format(src=src) + body, encoding="utf-8")
    return p


class Macros:
    """Every number the prose quotes. Names are letters only (LaTeX rule)."""

    def __init__(self):
        self.rows = []

    def __call__(self, name, value, src):
        assert name.isalpha(), name
        assert name not in {r["macro"] for r in self.rows}, f"duplicate macro {name}"
        self.rows.append(dict(macro=name, value=str(value), source=src))

    def tex(self):
        out = []
        for r in self.rows:
            out.append(f"\\newcommand{{\\{r['macro']}}}{{{r['value']}}}% {r['source']}\n")
        return "".join(out)


M = Macros()


def word(k):
    return ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine",
            "ten", "eleven", "twelve", "thirteen"][k] if k < 14 else str(k)


