def rq1_agreement(m, f):
    """Per benchmark and class group: range over arms of flow and conversation counts,
    and the range over arm pairs of the two Jaccard indices."""
    def rg(s, fmt):
        return rng(fmt(s.min()), fmt(s.max()))

    rows = []
    blocks = (("CICIDS2017", CIC_ARMS, "all", r"\cicids"),
              ("UNSW-NB15", UNSW_ARMS, "all", "UNSW-NB15"),
              ("UNSW-NB15", UNSW_ARMS, "unsw_dups_dropped", r"\begin{tabular}[t]{@{}l@{}}UNSW-NB15,\\duplicates dropped\end{tabular}"))
    for k, (bench, arms, var, name) in enumerate(blocks):
        for cls, lab in (("ALL", "All scored"), ("benign", "Benign"), ("ATTACK", "Attack")):
            mm = m[(m["variant"] == var) & (m["benchmark"] == bench) & (m["day"] == "ALL")
                   & (m["class"] == cls)]
            ff = f[(f["variant"] == var) & (f["benchmark"] == bench) & (f["day"] == "ALL")
                   & (f["class"] == cls) & (f["population"] == "own")].set_index("arm")
            fl, cv = ff.loc[arms, "flows"], ff.loc[arms, "conversations"]
            cj, fj = mm["conv_jaccard"], mm["flow_jaccard"]
            rows.append(" & ".join([
                name if cls == "ALL" else "", lab,
                rg(fl, n), f2(fl.max() / fl.min()), rg(cv, n), f2(cv.max() / cv.min()),
                rg(cj, f3), rg(fj, f3)]) + r" \\")
        if k < len(blocks) - 1:
            rows.append(r"\midrule")
    return (r"""\begin{sidewaystable}
\caption{Conversations agree, flows do not. Ranges over the arms of each benchmark (seven for
\cicids, three for UNSW-NB15), all scored days pooled. Max/min is the largest count divided by the
smallest. Jaccard indices range over every pair of arms; for flows, two records count as the same
object when the instrument pairs them.}\label{tab:rq1-agreement}
\small
\setlength{\tabcolsep}{3pt}
\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llrrrrrr@{}}
\toprule
 & & \multicolumn{2}{c}{Flows} & \multicolumn{2}{c}{Conversations} & \multicolumn{2}{c}{Jaccard over arm pairs} \\
\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}
Benchmark & Class & Range & Max/min & Range & Max/min & Conversations & Flows \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular*}
\end{sidewaystable}
""")


def rq1_fpc_class(f):
    ff = f[(f["variant"] == "all") & (f["day"] == "ALL") & (f["population"] == "common")]
    cic = ff[ff["benchmark"] == "CICIDS2017"]
    piv = cic.pivot(index="class", columns="arm", values="fpc")
    conv = cic[cic["arm"] == "lycos"].set_index("class")["conversations"]
    order = ["benign"] + sorted((c for c in piv.index if c in CLASS_NAME and c != "benign"),
                                key=lambda c: CLASS_NAME[c].lower())
    lines = []
    for c in order + ["MACRO_ATTACK"]:
        if c == "MACRO_ATTACK":
            lines.append(r"\midrule")
            name, cnt = "Macro mean, attacks", ""
        else:
            name, cnt = CLASS_NAME[c], n(conv[c])
        lines.append(" & ".join([name, cnt] + [f2(piv.loc[c, a]) for a in CIC_ARMS]) + r" \\")
    # the same mean without Heartbleed (one conversation), the rule of the detection macro-F1
    nohb = piv.loc[[c for c in order if c not in ("benign", "heartbleed")]].mean()
    lines.append(" & ".join(["Macro mean, without Heartbleed", ""] + [f2(nohb[a]) for a in CIC_ARMS]) + r" \\")
    heads = " & ".join(r"\rotatebox{90}{" + ARM_NAME[a] + "}" for a in CIC_ARMS)
    return (r"""\begin{table}[t]
\caption{Mean flows per conversation, \cicids, all days pooled, on the conversations present in
every arm, so each column describes the same traffic. Conv.: how many such conversations the class
has. The macro mean is the unweighted mean over attack classes, the average a macro-F1
inherits; the last row leaves out Heartbleed, a single conversation, as the macro-F1 of the
detection experiment does (Section~\ref{sec:protocol}).}\label{tab:rq1-fpc}
\small
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lr""" + "r" * len(CIC_ARMS) + r"""}
\toprule
Class & Conv. & """ + heads + r""" \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")


def rq1_alpha(a):
    aa = a[(a["day"] == "ALL") & (a["question"] == "labels") & (a["class"] == "ALL")
           & (a["population"] == "present_in_2plus")]
    lines = []
    for bench, var in (("CICIDS2017", "all"), ("UNSW-NB15", "all"), ("UNSW-NB15", "unsw_dups_dropped")):
        for lv, lab in (("multiclass", "Class"), ("binary", "Attack or benign"),
                        ("attempted_benign", "Attempted as benign")):
            if lv == "attempted_benign" and bench != "CICIDS2017":
                continue
